FIELDS = [
    "text", "dim", "border", "warn", "ok", "err", "key", "brand",
    "clusters", "jobs", "pipelines", "warehouses", "catalog",
]


def rust_hex(hexstr: str) -> str:
    return "0x" + hexstr.lstrip("#").upper()


def emit(variants: list[Variant], rev: str) -> str:
    out = [
        "// @generated by scripts/gen_parks_themes.py -- do not edit.",
        "//",
        "// Regenerate with:",
        "//     scripts/gen_parks_themes.py --parks-repo ../national-parks-themes --verify",
        "//",
        "// Source: https://github.com/pjhamera/national-parks-themes",
        "",
        "use super::{rgb, rgb3, Origin, Palette, Theme, ThemeKind};",
        "",
        "/// The parks-repo commit these palettes were generated from, so drift is",
        "/// detectable without re-deriving every colour.",
        f'pub const PARKS_SOURCE_REV: &str = "{rev}";',
        "",
        "pub static PARKS: &[Theme] = &[",
    ]

    for v in variants:
        kind = "Dark" if v.kind == "dark" else "Light"
        out += [
            "    Theme {",
            f'        id: "{v.id}",',
            f'        name: "{escape(v.display_name)}",',
            f"        kind: ThemeKind::{kind},",
            "        origin: Origin::Parks,",
            f'        keywords: "{escape(v.keywords)}",',
            "        palette: Palette {",
        ]
        for f in FIELDS:
            out.append(f"            {f}: rgb({rust_hex(getattr(v, f))}),")
        out.append(f"            grad_from: rgb3({rust_hex(v.grad_from)}),")
        out.append(f"            grad_to: rgb3({rust_hex(v.grad_to)}),")
        out.append(f"            bg: rgb({rust_hex(v.bg)}),")
        out += ["        },", "    },"]

    out += ["];", ""]
    return "\n".join(out)


def rustfmt(text: str) -> str:
    """Format through rustfmt so `cargo fmt` never rewrites what we emit --
    otherwise --check reports drift after every unrelated `cargo fmt`."""
    try:
        done = subprocess.run(
            ["rustfmt", "--edition", "2021", "--emit", "stdout"],
            input=text, capture_output=True, text=True, check=True,
        )
    except (FileNotFoundError, subprocess.CalledProcessError) as e:
        print(f"warning: rustfmt unavailable ({e}); emitting unformatted", file=sys.stderr)
        return text
    # rustfmt --emit stdout prefixes a filename banner when reading stdin.
    out = done.stdout
    if out.startswith("<stdin>:\n"):
        out = out[len("<stdin>:\n"):]
    return out


def escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


# ---------------------------------------------------------------------------
# Verification against upstream's own exports
# ---------------------------------------------------------------------------

# generated field -> ghostty key. Eleven of the thirteen Palette fields appear
# verbatim in files upstream produced with its own Lua. text/dim/border are
# compared pre-tint (`*_upstream`), so the tint cannot mask a ported-math bug.
GHOSTTY_MAP = [
    ("bg", "background"),
    ("text_upstream", "foreground"),
    ("dim_upstream", "palette 7"),
    ("border_upstream", "split-divider-color"),
    ("err", "palette 9"),
    ("ok", "palette 10"),
    ("warn", "palette 11"),
    ("warehouses", "palette 12"),
    ("jobs", "palette 13"),
    ("key", "palette 14"),
    ("accent_bright", "cursor-color"),
]


def parse_ghostty(path: Path) -> dict[str, str]:
    got = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        m = re.match(r"palette\s*=\s*(\d+)\s*=\s*(#[0-9a-fA-F]{6})", line)
        if m:
            got[f"palette {m.group(1)}"] = m.group(2).lower()
            continue
        m = re.match(r"([a-z-]+)\s*=\s*(#[0-9a-fA-F]{6})", line)
        if m:
            got[m.group(1)] = m.group(2).lower()
    return got


def verify(variants: list[Variant], repo: Path) -> int:
    mismatches, checked, skipped = 0, 0, 0
    for v in variants:
        path = repo / "terminal/ghostty" / v.id
        if not path.exists():
            print(f"  ! no ghostty export for {v.id}", file=sys.stderr)
            skipped += 1
            continue
        got = parse_ghostty(path)
        for field, key in GHOSTTY_MAP:
            if key not in got:
                print(f"  ! {v.id}: export has no {key!r}", file=sys.stderr)
                mismatches += 1
                continue
            mine = getattr(v, field).lower()
            if mine != got[key]:
                print(
                    f"  MISMATCH {v.id:<34} {field:<14} ours={mine} upstream={got[key]} ({key})",
                    file=sys.stderr,
                )
                mismatches += 1
            checked += 1

    print(f"verify: {checked} values checked across {len(variants) - skipped} themes, "
          f"{mismatches} mismatches")
    return mismatches


def report(variants: list[Variant]) -> None:
    """Contrast per theme, plus the text chroma the tint is there to move."""
    print(
        f"{'theme':<34} {'text':>6} {'dim':>6} {'brand':>6} "
        f"{'txtC':>6} {'was':>6} {'worst accent':>13}"
    )
    for v in variants:
        accents = {n: contrast(c, v.bg) for n, c in v.acc.items()}
        worst = min(accents.items(), key=lambda kv: kv[1])
        print(
            f"{v.id:<34} {contrast(v.text, v.bg):>6.2f} {contrast(v.dim, v.bg):>6.2f} "
            f"{contrast(v.brand, v.bg):>6.2f} {to_lch(v.text).c:>6.3f} "
            f"{to_lch(v.text_upstream).c:>6.3f} {worst[1]:>7.2f} {worst[0]}"
        )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--parks-repo",
        type=Path,
        default=Path(__file__).resolve().parent.parent.parent / "national-parks-themes",
        help="checkout of pjhamera/national-parks-themes (default: ../national-parks-themes)",
    )
    ap.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "src/theme/parks.rs",
    )
    ap.add_argument("--verify", action="store_true", help="diff against upstream's ghostty exports")
    ap.add_argument("--report", action="store_true", help="print achieved contrast ratios")
    ap.add_argument("--check", action="store_true", help="fail if the output file is out of date")
    args = ap.parse_args()

    repo = args.parks_repo.resolve()
    if not (repo / "lua/parks/palette/registry.lua").exists():
        raise SystemExit(f"not a parks checkout: {repo}")

    rev = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True,
    ).stdout.strip()

    variants = build_all(repo)
    text = rustfmt(emit(variants, rev))

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date -- rerun {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
    else:
        args.out.write_text(text)
        print(f"wrote {args.out}: {len(variants)} themes from {repo.name}@{rev[:8]}")

    if args.report:
        report(variants)

    if args.verify:
        if verify(variants, repo) > 0:
            return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
