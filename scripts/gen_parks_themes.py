class Variant:
    """One park in one variant: the Palette fields plus the few upstream
    intermediates --verify needs."""

    def __init__(self, park: Park, kind: str) -> None:
        self.park, self.kind = park, kind
        a = park.anchors if kind == "dark" else derive_light(park.anchors)
        self.anchors = a
        bg = a["bg"]

        # build_text: the muted tone blends the *raw* fg, then is floored.
        self.bg = bg
        self.text_upstream = ensure_contrast(a["fg"], bg, TEXT_CONTRAST)
        self.dim_upstream = ensure_contrast(mix(a["fg"], bg, 0.32), bg, MUTED_CONTRAST)
        # build.lua takes the border off the floored fg, not the raw anchor.
        self.border_upstream = mix(self.text_upstream, bg, 0.62)

        # The TUI tint: park identity has to survive in the foreground here,
        # because nothing paints `bg`. Chroma first, then re-floor -- raising
        # chroma can cost a little contrast, and the floors outrank the tint.
        # `to_hex` walks chroma back down when a hue cannot hold the target at
        # this lightness, so a gamut-bound blue simply lands as blue as it gets.
        self.text = ensure_contrast(
            tint(self.text_upstream, TINT_GAIN, TINT_FLOOR, TINT_CEIL), bg, TEXT_CONTRAST
        )
        self.dim = ensure_contrast(
            tint(self.dim_upstream, TINT_GAIN, TINT_FLOOR, TINT_CEIL), bg, MUTED_CONTRAST
        )
        # Borders stay derived from the tinted text, as upstream derives theirs
        # from the floored fg, so the chrome carries the same tone as the body.
        self.border = mix(self.text, bg, 0.62)

        acc = {n: ensure_contrast(a[n], bg, ACCENT_CONTRAST) for n in REQUIRED[2:]}
        self.acc = acc

        self.err, self.ok, self.warn, self.key = acc["red"], acc["green"], acc["yellow"], acc["cyan"]
        self.brand = acc["accent"]
        self.clusters, self.jobs = acc["cyan"], acc["purple"]
        self.pipelines, self.warehouses = acc["green"], acc["blue"]
        self.catalog = acc["orange"]
        self.grad_from, self.grad_to = acc["accent"], acc["orange"]

        # Not a Palette field; cursor-color in the exports pins `brand`.
        dir_ = 1 if kind == "dark" else -1

        def bright(lch):
            lch.l = min(max(lch.l + 0.09 * dir_, 0), 1)
            lch.c = lch.c * 1.06
            return lch

        self.accent_bright = adjust(self.brand, bright)

    @property
    def id(self) -> str:
        return f"parks-{self.park.slug}" + ("-light" if self.kind == "light" else "")

    @property
    def display_name(self) -> str:
        return self.park.name + (" Light" if self.kind == "light" else "")

    @property
    def keywords(self) -> str:
        words = [w.replace("_", " ") for w in self.park.states]
        words += re.sub(r"[^a-z0-9 ]", " ", self.park.blurb.lower()).split()
        if self.park.established:
            words.append(self.park.established)
        seen, out = set(), []
        for w in words:
            if w and w not in seen:
                seen.add(w)
                out.append(w)
        return " ".join(out)


def build_all(repo: Path) -> list[Variant]:
    registry = read_registry(repo)
    if len(registry) != 63:
        raise SystemExit(f"expected 63 parks in the registry, found {len(registry)}")

    variants = []
    for slug, name, dir_, states in registry:
        park = read_park(repo, slug, name, dir_, states)
        variants.append(Variant(park, "dark"))
        variants.append(Variant(park, "light"))

    if len(variants) != 126:
        raise SystemExit(f"expected 126 variants, built {len(variants)}")

    ids = [v.id for v in variants]
    if len(set(ids)) != len(ids):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        raise SystemExit(f"duplicate theme ids: {dupes}")
    pattern = re.compile(r"^parks-[a-z0-9-]+(-light)?$")
    bad = [i for i in ids if not pattern.match(i)]
    if bad:
        raise SystemExit(f"theme ids do not match the expected pattern: {bad}")

    # A floor sanity gate, deliberately below the 7.0 that ensure_contrast only
    # best-efforts -- this catches a broken port, not a stubborn park.
    for v in variants:
        t, d = contrast(v.text, v.bg), contrast(v.dim, v.bg)
        if t < 4.5:
            raise SystemExit(f"{v.id}: text contrast {t:.2f} is below the 4.5 floor")
        if d < 3.0:
            raise SystemExit(f"{v.id}: dim contrast {d:.2f} is below the 3.0 floor")

    return variants


