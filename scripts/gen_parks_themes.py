#!/usr/bin/env python3
"""Generate src/theme/parks.rs from a checkout of pjhamera/national-parks-themes.

The parks repo authors each of the 63 US National Parks as ten OKLCH anchors
(bg fg accent red orange yellow green cyan blue purple) and derives a light
variant from them mathematically. databricks-tui's Palette wants thirteen
colours plus two gradient endpoints, all drawn from that same set, so the
mapping is mechanical.

This script reimplements the subset of the upstream Lua colour math that the
mapping needs, rather than adding a colour crate to the binary: the palettes
are constants, so they are computed once here and committed as Rust.

    scripts/gen_parks_themes.py                  # regenerate src/theme/parks.rs
    scripts/gen_parks_themes.py --verify         # regenerate, then check the
                                                 # result against upstream's own
                                                 # terminal exports
    scripts/gen_parks_themes.py --report         # print achieved contrast ratios

--verify is the real correctness gate. The parks repo commits fully-resolved
ghostty schemes for all 126 variants, generated by the Lua this file ports, and
eleven of the thirteen Palette fields appear verbatim in them. A drifted mix(),
a missing gamut clip or a wrong derive_light constant shows up there as an
exact-value diff rather than as a colour nobody notices.

The one deliberate divergence from upstream is the TUI tint applied to text,
dim and border -- see TINT_GAIN below for why a TUI that never paints a
background needs it. It runs after the upstream values are computed and
--verify still diffs those, so the gate above stays exactly as strong.
"""

from __future__ import annotations

import argparse
import math
import re
import subprocess
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# OKLCH, ported from lua/parks/palette/oklch.lua
#
# Kept deliberately close to the Lua, including the constants and the shape of
# the gamut search, so the two can be compared line by line when upstream moves.
# ---------------------------------------------------------------------------


def clamp(v: float, lo: float, hi: float) -> float:
    return min(max(v, lo), hi)


def cbrt(v: float) -> float:
    """Cube root that keeps the sign of negative inputs."""
    if v < 0:
        return -((-v) ** (1 / 3))
    return v ** (1 / 3)


def to_linear(c: float) -> float:
    if c <= 0.04045:
        return c / 12.92
    return ((c + 0.055) / 1.055) ** 2.4


def to_gamma(c: float) -> float:
    if c <= 0.0031308:
        return c * 12.92
    return 1.055 * (c ** (1 / 2.4)) - 0.055


def hex_to_rgb(hexstr: str) -> tuple[float, float, float]:
    s = hexstr.lstrip("#")
    if len(s) != 6 or not re.fullmatch(r"[0-9a-fA-F]{6}", s):
        raise ValueError(f"invalid hex color {hexstr!r}")
    return (
        int(s[0:2], 16) / 255,
        int(s[2:4], 16) / 255,
        int(s[4:6], 16) / 255,
    )


def rgb_to_hex(r: float, g: float, b: float) -> str:
    return "#%02x%02x%02x" % (
        math.floor(clamp(r, 0, 1) * 255 + 0.5),
        math.floor(clamp(g, 0, 1) * 255 + 0.5),
        math.floor(clamp(b, 0, 1) * 255 + 0.5),
    )


def rgb_to_oklab(r: float, g: float, b: float) -> tuple[float, float, float]:
    lr, lg, lb = to_linear(r), to_linear(g), to_linear(b)

    l = 0.4122214708 * lr + 0.5363325363 * lg + 0.0514459929 * lb
    m = 0.2119034982 * lr + 0.6806995451 * lg + 0.1073969566 * lb
    s = 0.0883024619 * lr + 0.2817188376 * lg + 0.6299787005 * lb

    l_, m_, s_ = cbrt(l), cbrt(m), cbrt(s)

    return (
        0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_,
        1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_,
        0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_,
    )


def oklab_to_rgb(L: float, a: float, b: float) -> tuple[float, float, float]:
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b

    l, m, s = l_ * l_ * l_, m_ * m_ * m_, s_ * s_ * s_

    return (
        to_gamma(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s),
        to_gamma(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s),
        to_gamma(-0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s),
    )


class Lch:
    __slots__ = ("l", "c", "h")

    def __init__(self, l: float, c: float, h: float) -> None:
        self.l, self.c, self.h = l, c, h


def to_lch(hexstr: str) -> Lch:
    L, a, b = rgb_to_oklab(*hex_to_rgb(hexstr))
    c = math.sqrt(a * a + b * b)
    h = math.degrees(math.atan2(b, a))
    if h < 0:
        h += 360
    return Lch(L, c, h)


def in_gamut(l: float, c: float, h: float) -> bool:
    a = c * math.cos(math.radians(h))
    b = c * math.sin(math.radians(h))
    r, g, bl = oklab_to_rgb(l, a, b)
    eps = 1e-4
    return -eps <= r <= 1 + eps and -eps <= g <= 1 + eps and -eps <= bl <= 1 + eps


def to_hex(lch: Lch) -> str:
    """OKLCH back to hex, walking chroma down until the colour fits in sRGB.

    Clipping RGB instead would shift hue, which is the one thing the parks
    palettes are not allowed to do.
    """
    l = clamp(lch.l, 0, 1)
    h = lch.h % 360
    c = max(lch.c, 0)

    if not in_gamut(l, c, h):
        lo, hi = 0.0, c
        for _ in range(24):
            mid = (lo + hi) / 2
            if in_gamut(l, mid, h):
                lo = mid
            else:
                hi = mid
        c = lo

    a = c * math.cos(math.radians(h))
    b = c * math.sin(math.radians(h))
    return rgb_to_hex(*oklab_to_rgb(l, a, b))


def adjust(hexstr: str, fn) -> str:
    return to_hex(fn(to_lch(hexstr)))


def mix(a: str, b: str, t: float) -> str:
    """Blend in OKLab -- *not* OKLCH. Interpolating chroma and hue instead
    would swing through unrelated hues on the way between two colours."""
    t = clamp(t, 0, 1)
    l1, a1, b1 = rgb_to_oklab(*hex_to_rgb(a))
    l2, a2, b2 = rgb_to_oklab(*hex_to_rgb(b))
    r, g, bl = oklab_to_rgb(l1 + (l2 - l1) * t, a1 + (a2 - a1) * t, b1 + (b2 - b1) * t)
    return rgb_to_hex(clamp(r, 0, 1), clamp(g, 0, 1), clamp(bl, 0, 1))


def tint(hexstr: str, gain: float, floor: float, ceil: float) -> str:
    """Raise a near-neutral colour's chroma without touching its hue.

    Scaling rather than assigning keeps upstream's relative intent -- Grand
    Canyon was authored richer than Yosemite and stays richer -- while the floor
    guarantees no park lands back in grey and the ceiling stops the loudest
    parks from turning body text into an accent.
    """
    lch = to_lch(hexstr)
    lch.c = clamp(lch.c * gain, floor, ceil)
    return to_hex(lch)


def luminance(hexstr: str) -> float:
    r, g, b = hex_to_rgb(hexstr)
    return 0.2126 * to_linear(r) + 0.7152 * to_linear(g) + 0.0722 * to_linear(b)


def contrast(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    if la < lb:
        la, lb = lb, la
    return (la + 0.05) / (lb + 0.05)


def ensure_contrast(fg: str, bg: str, ratio: float) -> str:
    """Nudge `fg` along lightness until it clears `ratio` against `bg`.

    Best-effort, not a guarantee: it gives up after 50 steps or at the ends of
    the lightness range and returns the best it reached.
    """
    if contrast(fg, bg) >= ratio:
        return fg

    lch = to_lch(fg)
    bg_l = to_lch(bg).l
    step = 0.02 if bg_l < 0.5 else -0.02
    best, best_ratio = fg, contrast(fg, bg)

    for _ in range(50):
        lch.l = clamp(lch.l + step, 0, 1)
        candidate = to_hex(lch)
        got = contrast(candidate, bg)
        if got > best_ratio:
            best, best_ratio = candidate, got
        if got >= ratio:
            return candidate
        if lch.l <= 0 or lch.l >= 1:
            break

    return best


