REQUIRED = ["bg", "fg", "accent", "red", "orange", "yellow", "green", "cyan", "blue", "purple"]

# Contrast floors, from build.lua's M.CONTRAST.
TEXT_CONTRAST = 7.0
MUTED_CONTRAST = 4.5
ACCENT_CONTRAST = 4.5

# --- The TUI tint (databricks-tui only, not upstream) ----------------------
#
# Upstream authors `fg` for a terminal that also paints its `bg`, so a park's
# character can live in the background and the foreground can stay near-neutral.
# This TUI never paints a background -- it inherits the terminal's -- so the
# only thing on screen carrying a park's identity is its foreground, and text /
# dim / border are most of the pixels. Shipped untouched, all 63 parks render
# body text at OKLCH chroma 0.017 on average, which is grey: the palettes are
# distinguishable in the swatch strip and nowhere else.
#
# The fix keeps each park's authored *hue* -- it already tracks that park's own
# bg hue closely -- and only raises its chroma, so text reads as iced blue on
# Denali and sandstone on Zion. For calibration, the built-ins nobody complains
# about sit at chroma 0.039 (kanagawa) to 0.061 (tokyo-night); the floor and
# ceiling below bracket that range.
#
# Applied after the upstream values are computed, never before: --verify still
# diffs the pre-tint colours against upstream's own exports.
TINT_GAIN = 2.4  # multiplier on the park's authored chroma
TINT_FLOOR = 0.030  # lift the near-neutral parks (Yosemite, Gateway Arch) into visibility
TINT_CEIL = 0.060  # keep the already-saturated parks (Zion, Arches) from shouting

# derive_light's targets, from build.lua's LIGHT table.
LIGHT_BG_L = 0.955
LIGHT_BG_CHROMA = 2.2
LIGHT_BG_CHROMA_CAP = 0.020
LIGHT_FG_L = 0.30
LIGHT_FG_CHROMA_CAP = 0.055
LIGHT_ACCENT_L = 0.52
LIGHT_ACCENT_SPREAD = 0.85
LIGHT_ACCENT_CHROMA = 1.12

ENTRY_RE = re.compile(
    r'\{\s*slug\s*=\s*"([^"]+)"\s*,\s*name\s*=\s*"([^"]+)"\s*,\s*'
    r'dir\s*=\s*"([^"]+)"\s*,\s*states\s*=\s*\{([^}]*)\}\s*,?\s*\}'
)


class Park:
    def __init__(self, slug, name, dir_, states, blurb, established, anchors):
        self.slug, self.name, self.dir = slug, name, dir_
        self.states, self.blurb = states, blurb
        self.established, self.anchors = established, anchors


def read_registry(repo: Path) -> list[tuple[str, str, str, list[str]]]:
    src = (repo / "lua/parks/palette/registry.lua").read_text()
    out = []
    for slug, name, dir_, states in ENTRY_RE.findall(src):
        out.append((slug, name, dir_, re.findall(r'"([^"]+)"', states)))
    return out


def read_park(repo: Path, slug: str, name: str, dir_: str, states: list[str]) -> Park:
    # Slugs are hyphenated but Lua module files are not: gates-of-the-arctic
    # lives at alaska/gates_of_the_arctic.lua.
    path = repo / "lua/parks/parks" / dir_ / f"{slug.replace('-', '_')}.lua"
    if not path.exists():
        raise SystemExit(f"missing palette file for {slug}: {path}")
    src = path.read_text()

    body = re.search(r"\bdark\s*=\s*\{(.*?)\n  \}", src, re.S)
    if not body:
        raise SystemExit(f"{slug}: could not find the `dark` anchor table")

    anchors = dict(re.findall(r'^\s*(\w+)\s*=\s*"(#[0-9a-fA-F]{6})"', body.group(1), re.M))
    missing = [k for k in REQUIRED if k not in anchors]
    if missing:
        raise SystemExit(f"{slug}: missing required anchors {missing}")
    extra = [k for k in anchors if k not in REQUIRED]
    if extra:
        # derive_light averages over every non-bg/fg anchor, so an unexpected
        # one would silently move every light colour.
        raise SystemExit(f"{slug}: unexpected extra anchors {extra}")

    if re.search(r"^\s*light\s*=\s*\{", src, re.M):
        raise SystemExit(
            f"{slug}: declares a `light = {{}}` override, which this generator "
            f"does not implement -- add it before regenerating"
        )

    blurb_m = re.search(r'^\s*blurb\s*=\s*"([^"]*)"', src, re.M)
    est_m = re.search(r"^\s*established\s*=\s*(\d+)", src, re.M)
    return Park(
        slug,
        name,
        dir_,
        states,
        blurb_m.group(1) if blurb_m else "",
        est_m.group(1) if est_m else "",
        anchors,
    )


def derive_light(dark: dict[str, str]) -> dict[str, str]:
    """Port of build.lua's derive_light. Hue is carried over untouched."""
    light = {}

    def bg_fn(lch):
        lch.l = LIGHT_BG_L
        lch.c = min(lch.c * LIGHT_BG_CHROMA, LIGHT_BG_CHROMA_CAP)
        return lch

    def fg_fn(lch):
        lch.l = LIGHT_FG_L
        lch.c = min(lch.c, LIGHT_FG_CHROMA_CAP)
        return lch

    light["bg"] = adjust(dark["bg"], bg_fn)
    light["fg"] = adjust(dark["fg"], fg_fn)

    accents = [n for n in dark if n not in ("bg", "fg")]
    mean_l = (
        sum(to_lch(dark[n]).l for n in accents) / len(accents) if accents else LIGHT_ACCENT_L
    )

    for name in accents:
        def accent_fn(lch, _mean=mean_l):
            lch.l = LIGHT_ACCENT_L - (lch.l - _mean) * LIGHT_ACCENT_SPREAD
            lch.c = lch.c * LIGHT_ACCENT_CHROMA
            return lch

        light[name] = adjust(dark[name], accent_fn)

    return light


